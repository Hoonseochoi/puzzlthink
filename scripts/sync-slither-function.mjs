// Copies the Slitherlink engine into the slither-finish Edge Function (Deno needs file extensions in imports).
// Run after changing src/lib/slitherlink.ts or the rng in src/lib/nemoCount.ts:  node scripts/sync-slither-function.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const dir = 'supabase/functions/slither-finish';
const head = '// Generated by scripts/sync-slither-function.mjs: do not edit here.\n';
const engine = readFileSync('src/lib/slitherlink.ts', 'utf8').replace("from './nemoCount';", "from './rng.ts';");
writeFileSync(`${dir}/slitherlink.ts`, head + engine);
const nemo = readFileSync('src/lib/nemoCount.ts', 'utf8');
const rng = nemo.slice(nemo.indexOf('export function rng('), nemo.indexOf('type Rand'));
writeFileSync(`${dir}/rng.ts`, head + rng.trimEnd() + '\n');
console.log('synced', dir);
