/** 이/가 after a name ("나" → "내가"; "AI · 어려움" → "AI · 어려움이"). Digits read in Korean; anything else gets "이(가)". */
function iga(name: string) {
  const base = name.replace(/\s*\([^)]*\)$/, '').trim();
  if (base === '나') return '내가';
  const last = base.slice(-1);
  const code = last.charCodeAt(0);
  let batchim: boolean | null = null;
  if (code >= 0xac00 && code <= 0xd7a3) batchim = (code - 0xac00) % 28 !== 0;
  else if (/[0-9]/.test(last)) batchim = '0136780'.includes(last);
  return `${name}${batchim === null ? '이(가)' : batchim ? '이' : '가'}`;
}

